#!/usr/bin/env bash
#
# Renders test/golden/rfb/expected/ from the official Receita Federal calculators.
#
#   scripts/conformance/rfb_calculator.sh
#
# It clones (or updates) the two calculators, generates the SQLite database, builds and
# runs both in containers on localhost, waits for them, runs
# scripts/conformance/render_rfb.exs and tears the containers down. Idempotent: what is
# already built for the pinned commits is reused.
#
# Prerequisites
#   * a container runtime: rootless podman or docker (CONTAINER_RUNTIME, else podman if
#     installed, else docker). Java is never installed on the host: it runs only inside
#     the images eclipse-temurin:25-jre and maven:3-eclipse-temurin-25 (pulled on first use)
#   * git, curl, and Elixir/OTP as in mix.exs (deps fetched)
#   * network access to github.com, Maven Central and the image registry
#   * ports 18080 and 18082 on 127.0.0.1 free (RFB_REGIME_PORT, RFB_SIMPLES_PORT)
#   With docker the files of the cache are owned by root; use podman rootless locally.
#
# Environment (all optional)
#   RFB_REGIME_REF   commit of ReceitaFederal/calculadora-rtc-regime-regular to render, or
#                    `latest` (head of its default branch). Default: the pinned commit below
#   RFB_SIMPLES_REF  same, for calculadora-rtc-simples-nacional
#   RFB_CACHE        where repos, builds and the Maven cache live
#                    (default $HOME/.cache/sefaz_nfe/rfb), never inside the worktree
#   MIX_CMD          how to run mix (default `mix`)
#
# The third RFB repository (calculadora-rtc-danfse, the DANFSe generator, Go) is not used
# here: it renders documents, it does not compute taxes. See test/golden/rfb/README.md.

set -euo pipefail

# Pinned commits: bump them together with the rendered files (test/golden/rfb/expected).
PINNED_REGIME_REF="f1eebd7ce3157423b1a6aaca7dc1d6c3395452c4"
PINNED_SIMPLES_REF="a926d5a76095ac0295a6612a9a54db7ffead2396"

REGIME_URL="https://github.com/ReceitaFederal/calculadora-rtc-regime-regular.git"
SIMPLES_URL="https://github.com/ReceitaFederal/calculadora-rtc-simples-nacional.git"
MAVEN_IMAGE="docker.io/library/maven:3-eclipse-temurin-25"
JRE_IMAGE="docker.io/library/eclipse-temurin:25-jre"

REGIME_PORT="${RFB_REGIME_PORT:-18080}"
SIMPLES_PORT="${RFB_SIMPLES_PORT:-18082}"
CACHE="${RFB_CACHE:-$HOME/.cache/sefaz_nfe/rfb}"
MIX_CMD="${MIX_CMD:-mix}"
HEALTH_TIMEOUT="${RFB_HEALTH_TIMEOUT:-240}"

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
START=$SECONDS

log() { printf '==> %s\n' "$*" >&2; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }

# --- container runtime -------------------------------------------------------------

RT="${CONTAINER_RUNTIME:-}"
if [ -z "$RT" ]; then
  if command -v podman >/dev/null 2>&1; then RT=podman
  elif command -v docker >/dev/null 2>&1; then RT=docker
  else die "neither podman nor docker found (set CONTAINER_RUNTIME)"; fi
fi
command -v "$RT" >/dev/null 2>&1 || die "container runtime '$RT' not found"
"$RT" info >/dev/null 2>&1 || die "'$RT info' failed: the runtime is not usable by this user"

# SELinux relabelling of bind mounts, only where podman runs under an enforcing policy.
Z=""
if [ "$RT" = podman ] && command -v getenforce >/dev/null 2>&1 && [ "$(getenforce)" = Enforcing ]; then
  Z=":Z"
fi
log "runtime: $RT"

# --- repositories at pinned commits --------------------------------------------------

mkdir -p "$CACHE/m2"

# checkout <name> <url> <ref>   (prints the commit)
checkout() {
  local name=$1 url=$2 ref=$3 dir="$CACHE/$1"
  if [ ! -d "$dir/.git" ]; then
    git clone -q "$url" "$dir" >&2
  fi
  git -C "$dir" fetch -q --tags origin >&2
  if [ "$ref" = latest ]; then
    ref="$(git -C "$dir" rev-parse origin/HEAD)"
  fi
  git -C "$dir" checkout -q --detach "$ref" >&2
  git -C "$dir" rev-parse HEAD
}

REGIME_SHA="$(checkout calculadora-rtc-regime-regular "$REGIME_URL" "${RFB_REGIME_REF:-$PINNED_REGIME_REF}")"
SIMPLES_SHA="$(checkout calculadora-rtc-simples-nacional "$SIMPLES_URL" "${RFB_SIMPLES_REF:-$PINNED_SIMPLES_REF}")"
REGIME_DIR="$CACHE/calculadora-rtc-regime-regular"
SIMPLES_DIR="$CACHE/calculadora-rtc-simples-nacional"
log "regime-regular   $REGIME_SHA"
log "simples-nacional $SIMPLES_SHA"

# --- build ----------------------------------------------------------------------------

maven() { # maven <dir> <args...>
  local dir=$1; shift
  "$RT" run --rm -v "$dir:/work$Z" -v "$CACHE/m2:/root/.m2$Z" -w /work "$MAVEN_IMAGE" mvn -B -q "$@"
}

# The database is generated by the regime-regular repository's Flyway scripts (the
# simples-nacional README sends you there); the jar of each application is built from its
# own repository. A stamp keeps a rebuild from happening when nothing changed.
STAMP_REGIME="$REGIME_DIR/.rfb-stamp"
if [ "$(cat "$STAMP_REGIME" 2>/dev/null)" != "$REGIME_SHA" ] \
  || [ ! -f "$REGIME_DIR/target/api-regime-geral.jar" ] || [ ! -f "$REGIME_DIR/calculadora/db/calculadora-pro.db" ]; then
  log "regime-regular: generating the database and building"
  rm -rf "$REGIME_DIR/calculadora/db" "$REGIME_DIR/target"
  mkdir -p "$REGIME_DIR/calculadora/db"
  maven "$REGIME_DIR" flyway:migrate -Dflyway.configFiles=./flyway/flyway-pro.conf --errors
  maven "$REGIME_DIR" package -DskipTests
  echo "$REGIME_SHA" >"$STAMP_REGIME"
fi

STAMP_SIMPLES="$SIMPLES_DIR/.rfb-stamp"
WANT_SIMPLES="$SIMPLES_SHA+$REGIME_SHA"
if [ "$(cat "$STAMP_SIMPLES" 2>/dev/null)" != "$WANT_SIMPLES" ] \
  || [ ! -f "$SIMPLES_DIR/target/api-simples-nacional.jar" ] || [ ! -f "$SIMPLES_DIR/calculadora/db/calculadora-pro.db" ]; then
  log "simples-nacional: copying the database and building"
  rm -rf "$SIMPLES_DIR/calculadora/db" "$SIMPLES_DIR/target"
  mkdir -p "$SIMPLES_DIR/calculadora/db"
  cp "$REGIME_DIR/calculadora/db/calculadora-pro.db" "$SIMPLES_DIR/calculadora/db/"
  maven "$SIMPLES_DIR" package -DskipTests
  echo "$WANT_SIMPLES" >"$STAMP_SIMPLES"
fi

# --- run ------------------------------------------------------------------------------

NAME_REGIME="rfb-regime-$$"
NAME_SIMPLES="rfb-simples-$$"

teardown() {
  "$RT" rm -f "$NAME_REGIME" "$NAME_SIMPLES" >/dev/null 2>&1 || true
}
trap teardown EXIT

start() { # start <name> <dir> <host port> <container port> <jar>
  "$RT" run -d --name "$1" -p "127.0.0.1:$3:$4" -v "$2:/work$Z" -w /work "$JRE_IMAGE" \
    java -Dspring.profiles.active=offline -jar "target/$5" >/dev/null
}

log "starting the calculators on 127.0.0.1:$REGIME_PORT and 127.0.0.1:$SIMPLES_PORT"
start "$NAME_REGIME" "$REGIME_DIR" "$REGIME_PORT" 8080 api-regime-geral.jar
start "$NAME_SIMPLES" "$SIMPLES_DIR" "$SIMPLES_PORT" 8082 api-simples-nacional.jar

REGIME_API="http://127.0.0.1:$REGIME_PORT/api/calculadora"
SIMPLES_API="http://127.0.0.1:$SIMPLES_PORT/api"

wait_for() { # wait_for <container> <url>
  local deadline=$((SECONDS + HEALTH_TIMEOUT))
  until curl -fsS -o /dev/null "$2" 2>/dev/null; do
    if [ "$("$RT" inspect -f '{{.State.Running}}' "$1" 2>/dev/null)" != true ]; then
      "$RT" logs "$1" 2>&1 | tail -30 >&2
      die "container $1 stopped"
    fi
    if [ "$SECONDS" -ge "$deadline" ]; then
      "$RT" logs "$1" 2>&1 | tail -30 >&2
      die "timed out waiting for $2"
    fi
    sleep 2
  done
}

wait_for "$NAME_REGIME" "$REGIME_API/dados-abertos/versao"
wait_for "$NAME_SIMPLES" "$SIMPLES_API/versao"
log "healthy after $((SECONDS - START))s"

# --- render ---------------------------------------------------------------------------

cd "$ROOT"
log "rendering test/golden/rfb/expected"
# shellcheck disable=SC2086
MIX_ENV=test \
  RFB_REGIME_URL="$REGIME_API" \
  RFB_SIMPLES_URL="$SIMPLES_API" \
  RFB_REGIME_SHA="$REGIME_SHA" \
  RFB_SIMPLES_SHA="$SIMPLES_SHA" \
  $MIX_CMD run scripts/conformance/render_rfb.exs

log "done in $((SECONDS - START))s"
